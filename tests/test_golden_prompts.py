"""Golden tests: the compiler must reproduce the bundle's generated fixtures.

The renders in prompts/turn_message/ were produced by the production
TurnBuilder but carry independently-anonymized identity values (session id
`8f3c...`, guard id `4021`) that differ from the ids recorded in the shift's
tool calls (`16e1...`, `9674`). The tests therefore inject the render's
identity values and require byte-for-byte equality on everything else:
structure, static text, section joining, and computed local times.
"""

from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path

import pytest

from harness.loader import load_shift, parse_ts
from harness.prompts import GuardRef, compile_system_prompt, compile_turn_message

BUNDLE = Path(__file__).resolve().parents[1]
PROMPTS = BUNDLE / "prompts"
RENDERS = PROMPTS / "turn_message"

# Identity values used by the checked-in renders (see module docstring).
RENDER_SESSION_ID = "8f3c1d42-0b77-4e19-9a52-6c1e2f0ad7b3"
RENDER_GUARDS = [GuardRef(name="Hector Nguyen", id="4021")]


def strip_header_comment(text: str) -> str:
    """Drop the `<!-- Rendered by ... -->` / `<!-- Generated by ... -->`
    comment (and following blank line) that marks derived files."""
    return re.sub(r"\A<!--.*?-->\n\n?", "", text, flags=re.DOTALL)


@pytest.fixture(scope="module")
def shift():
    return load_shift(BUNDLE / "shifts" / "56370.json")


def build_kwargs(shift, turn: int, trigger: str, ts: datetime, **overrides):
    kwargs = dict(
        turn=turn,
        trigger=trigger,
        ts=ts,
        session_id=RENDER_SESSION_ID,
        job_id=shift.id,
        guards=RENDER_GUARDS,
        shift_start=shift.start,
        shift_end=shift.end,
        tz_name=shift.timezone,
    )
    kwargs.update(overrides)
    return kwargs


def test_system_prompt_matches_assembled_fixture():
    expected = strip_header_comment(
        (PROMPTS / "ASSEMBLED_SYSTEM_PROMPT.md").read_text(encoding="utf-8")
    )
    # Passing the literal placeholder reproduces the checked-in assembly.
    actual = compile_system_prompt(PROMPTS, "{COPILOT_CONTEXT}")
    assert actual.strip("\n") == expected.strip("\n")


def test_system_prompt_substitutes_context():
    actual = compile_system_prompt(PROMPTS, "CONTEXT SENTINEL")
    assert "CONTEXT SENTINEL" in actual
    assert "{COPILOT_CONTEXT}" not in actual


# The seven renders produced from real turns of shift 56370. Timestamps are
# taken from the render header comments and match baseline turn_start entries.
REAL_RENDER_CASES = [
    ("session_start.md", 1, "session_start", "2026-08-04T21:01:09.512506+00:00",
     dict(first_turn=True)),
    ("guard_in_transit.md", 2, "guard_in_transit", "2026-08-04T21:09:47.531552+00:00",
     dict()),
    ("job_event.md", 3, "job_event", "2026-08-04T21:19:12.312394+00:00",
     dict()),
    ("guard_checked_in.md", 5, "guard_checked_in", "2026-08-04T23:24:12.148884+00:00",
     dict()),
    ("guard_message.md", 20, "guard_message", "2026-08-05T02:29:56.017231+00:00",
     dict()),
    ("shift_ending.md", 40, "shift_ending", "2026-08-05T09:53:31.608547+00:00",
     dict()),
]


@pytest.mark.parametrize(
    "render_name, turn, trigger, ts_str, extra",
    REAL_RENDER_CASES,
    ids=[c[0] for c in REAL_RENDER_CASES],
)
def test_turn_message_matches_render(shift, render_name, turn, trigger, ts_str, extra):
    expected = strip_header_comment(
        (RENDERS / render_name).read_text(encoding="utf-8")
    )
    if extra.get("first_turn"):
        extra.setdefault("site_account", shift.context["site"]["account"])
        extra.setdefault("site_address", shift.context["site"]["address"])
    actual = compile_turn_message(
        PROMPTS, **build_kwargs(shift, turn, trigger, parse_ts(ts_str), **extra)
    )
    assert actual == expected


def test_scheduled_check_in_matches_render_with_gate_block(shift):
    """The scheduled_check_in render includes a 'Why you woke this cycle'
    section whose content came from the (lost) gate record; the test injects
    that block verbatim and verifies placement and joining around it."""
    expected = strip_header_comment(
        (RENDERS / "scheduled_check_in.md").read_text(encoding="utf-8")
    )
    match = re.search(
        r"## Why you woke this cycle\n.*?just because you woke\.", expected, re.DOTALL
    )
    assert match, "gate block not found in render"
    actual = compile_turn_message(
        PROMPTS,
        **build_kwargs(
            shift, 29, "scheduled_check_in",
            parse_ts("2026-08-05T04:00:56.590731+00:00"),
            gate_block=match.group(0),
        ),
    )
    assert actual == expected


